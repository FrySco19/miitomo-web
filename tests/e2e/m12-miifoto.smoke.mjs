// M10–M12 smoke test (PLAY): closet with original names/thumbnails + closet camera, Miifoto composer from the original
// archCamera data (pose table from MSBT attributes, faces, backgrounds, stamps, fonts, templates), PNG export.
// Usage: node tests/e2e/m12-miifoto.smoke.mjs <url> <outDir> <file1> [file2...]
import { chromium } from 'playwright';
import { mkdirSync, writeFileSync } from 'node:fs';
const [url, out, ...files] = process.argv.slice(2);
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: 1400, height: 900 }, acceptDownloads: true });
const page = await ctx.newPage();
const logs = [];
page.on('console', (m) => { if (m.type() !== 'debug') logs.push(`${m.type()}: ${m.text()}`); });
page.on('pageerror', (e) => logs.push(`pageerror: ${e.message}`));
const checks = {}; const fail = [];
const expect = (n, ok, info) => { checks[n] = { ok: !!ok, info }; if (!ok) fail.push(`${n}: ${JSON.stringify(info)}`); };
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` });
await page.goto(url);
await page.waitForFunction(() => window.__mtw?.play?.currentScreen === 'setup', null, { timeout: 60000 });
await page.setInputFiles('#play input[type=file]', files);
await page.waitForFunction(() => window.__mtw.play.currentScreen === 'create', null, { timeout: 300000 });
await page.click('#play [data-a=next]'); await page.fill('#play .pl-input', 'Kelly'); await page.click('#play [data-a=next]');
await page.selectOption('#play select[data-k=m]', '5'); await page.selectOption('#play select[data-k=d]', '2'); await page.click('#play [data-a=ok]');
await page.waitForFunction(() => window.__mtw.play.currentScreen === 'personality', null, { timeout: 20000 }); await page.click('#play [data-a=ok]');
await page.waitForFunction(() => window.__mtw.director && window.__mtw.play.currentScreen === 'room', null, { timeout: 120000 });
await page.evaluate(() => { window.__mtw.testClock.paused = true; });
await page.evaluate(() => window.__mtw.simRoom(14));
await page.evaluate(() => { window.__mtw.roomUi.close(true); });
// closet with thumbnails (dated zips present)
await page.click('#play .pl-tab[data-tab=menu]'); await page.click('#play .pl-mbtn[data-a=closet]');
await page.click('#play .pl-ctab[data-tab=acce]').catch(() => {});
await page.waitForTimeout(800); await page.evaluate(() => window.__mtw.simRoom(0.5));
const cl = await page.evaluate(() => ({ items: document.querySelectorAll('#play .pl-citem').length, imgs: document.querySelectorAll('#play .pl-citem img').length, closetCam: window.__mtw.camera?.fov }));
await shot('m12-01-closet-thumbs');
expect('closet shows thumbnails when the capture2 files are imported', cl.items > 0 && cl.imgs > 0, cl);
await page.click('#play .pl-close');
// Miifoto
await page.click('#play .pl-tab[data-tab=menu]');
expect('Miifoto enabled', !(await page.evaluate(() => document.querySelector('#play .pl-mbtn[data-a=foto]').disabled)), null);
await page.click('#play .pl-mbtn[data-a=foto]');
await page.waitForFunction(() => window.__mtw.play.currentScreen === 'miifoto', null, { timeout: 30000 });
await page.waitForFunction(() => !!window.__mtw.play.miiLayerReady?.() || document.querySelector('.pf-busy')?.hidden, null, { timeout: 60000 });
await page.waitForTimeout(1500);
const poses = await page.evaluate(() => [...document.querySelectorAll('[data-pose]')].map((b) => b.textContent));
expect('poses from ArchCameraAnimation (88, original names)', poses.length >= 80 && poses.includes('Saluto'), poses.slice(0, 6));
await page.click('[data-pose=waveHand]'); await page.waitForTimeout(2500);
await page.click('.pf-tabs [data-t=face]'); const facesN = await page.evaluate(() => document.querySelectorAll('[data-face]').length);
await page.click('[data-face="7"]'); await page.waitForTimeout(2500);
expect('faces from ArchCameraFace (≥40)', facesN >= 40, facesN);
await page.click('.pf-tabs [data-t=bg]'); const bgN = await page.evaluate(() => document.querySelectorAll('[data-bg]').length);
await page.click('[data-bg="037"]').catch(async () => { await page.click('[data-bg]'); }); await page.waitForTimeout(800);
expect('backgrounds (214)', bgN >= 100, bgN);
await page.click('.pf-tabs [data-t=stamp]'); await page.click('[data-stamp]'); await page.waitForTimeout(600);
await page.click('.pf-tabs [data-t=text]'); await page.fill('.pf-text', 'Ciao da Kelly!'); await page.click('[data-a=addtext]'); await page.waitForTimeout(800);
await shot('m12-02-miifoto-edit');
const px = await page.evaluate(() => { const c = document.querySelector('.pf-canvas'); const d = c.getContext('2d').getImageData(0, 0, 640, 640).data; let colored = 0; for (let i = 0; i < d.length; i += 4 * 97) if (!(d[i] > 245 && d[i + 1] > 245 && d[i + 2] > 245)) colored++; return colored; });
expect('photo canvas rendered (not blank)', px > 500, px);
const miiPx = await page.evaluate(() => window.__mtw.play.miiPixels?.());
expect('Mii layer rendered (opaque pixels)', (miiPx ?? 0) > 2000, miiPx);
// template
await page.click('.pf-tabs [data-t=tpl]'); const tpls = await page.evaluate(() => document.querySelectorAll('[data-tpl]').length);
await page.click('[data-tpl=N04]').catch(async () => { await page.click('[data-tpl]'); }); await page.waitForTimeout(3000);
await shot('m12-03-miifoto-template');
expect('templates (89)', tpls >= 80, tpls);
await page.evaluate(() => { const p = window.__mtw.play; p.photo.stamps = []; p.photo.texts = []; p.photo.bg = '010'; });
await page.click('.pf-tabs [data-t=pose]'); await page.click('[data-pose=stand1]'); await page.waitForTimeout(2500);
await shot('m12-03b-miifoto-pose-stand1');
await page.click('.pf-tabs [data-t=face]'); await page.click('[data-face="1"]'); await page.waitForTimeout(2500);
await page.click('.pf-tabs [data-t=pose]'); await page.click('[data-pose=cheer]'); await page.waitForTimeout(2500);
await shot('m12-03c-miifoto-cheer-smile');
const dl = page.waitForEvent('download', { timeout: 15000 });
await page.click('[data-a=savephoto]');
const d = await dl; await d.saveAs(`${out}/m12-04-export.png`);
expect('PNG export', /\.png$/.test(d.suggestedFilename()), d.suggestedFilename());
await page.click('[data-a=close]');
await page.waitForFunction(() => window.__mtw.play.currentScreen === 'room' && window.__mtw.director, null, { timeout: 60000 });
await page.evaluate(() => window.__mtw.simRoom(3));
await shot('m12-05-back-to-room');
const errors = logs.filter((l) => /^(error|pageerror)/.test(l));
expect('zero console errors', errors.length === 0, errors);
writeFileSync(`${out}/report.json`, JSON.stringify({ checks, fail, logs }, null, 1));
console.log(JSON.stringify({ passed: Object.values(checks).filter((c) => c.ok).length, total: Object.keys(checks).length, fail, logs: logs.filter((l) => /error|warn/i.test(l)).slice(0, 15) }, null, 1));
await browser.close();
process.exit(fail.length ? 1 : 0);
